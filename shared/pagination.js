/**
 * عدد الصفحات لإجمالي نتائج معلوم. لا تقلّ أبدًا عن 1: قائمة فارغة
 * تبقى «صفحة واحدة فارغة» لا صفر صفحة — وإلا صارت الصفحة الحالية (1)
 * خارج المدى بحسابنا نحن.
 * @param {number} totalCount إجمالي النتائج المطابقة في القاعدة
 * @param {number} perPage    حجم الصفحة
 * @returns {number} عدد الصفحات (≥ 1)
 */
function totalPagesOf(totalCount, perPage) {
  const size = Math.max(1, Number(perPage) || 1);
  return Math.max(1, Math.ceil((Number(totalCount) || 0) / size));
}

/**
 * يحصر رقم صفحة داخل المدى الصالح [1, totalPagesOf(...)].
 * يستوعب المدخلات الفاسدة (nan/سالب/كسري/نصّي) لأنه قد يستقبل قيمًا
 * من الواجهة أو من روابط خارجية.
 * @param {number} page       الصفحة المطلوبة
 * @param {number} totalCount إجمالي النتائج المطابقة
 * @param {number} perPage    حجم الصفحة
 * @returns {number} رقم صفحة صالح دائمًا
 */
function clampPage(page, totalCount, perPage) {
  const wanted = Math.floor(Number(page)) || 1;
  return Math.min(Math.max(1, wanted), totalPagesOf(totalCount, perPage));
}
