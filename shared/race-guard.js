/* ================================================================
   🚦 shared/race-guard.js — حارس تزامن للطلبات غير المتزامنة
   ================================================================
   المشكلة التي يحلّها
   ───────────────────
   أي دالة على النمط «اقرأ الحالة → انتظر الشبكة → اكتب النتيجة على
   الواجهة» معرَّضة لعطل بنيوي: لو أُطلقت مرتين بتقارب، فترتيب وصول
   الاستجابتين لا يلزم أن يطابق ترتيب إرسالهما (شبكة أبطأ، استعلام
   أثقل، إعادة محاولة داخلية). فتصل الاستجابة الأقدم بعد الأحدث
   وتكتب فوقها، فيرى المستخدم نتيجةً لا تمثّل آخر إجراء قام به.

   العطل ليس في مكان الاستدعاء بل في **الفجوة الزمنية بين القراءة
   والكتابة**، لذلك الحلّ يجب أن يسكن تلك الفجوة لا أن يعالج كل
   مُستدعٍ على حدة.

   ما لا يفعله
   ───────────
   لا يُلغي الطلبات الجارية ولا يوفّر شبكة — الاستجابة المتجاوَزة
   تصل ثم تُهمَل. الغرض **صحّة الحالة** لا توفير الطلبات، والإلغاء
   يحتاج AbortSignal عبر كل طبقة ويضيف تعقيدًا لا تستدعيه الفائدة
   عند هذا الحجم من الطلبات.

   الاستعمال
   ─────────
     const race = createRaceGuard();

     async function load() {
       const isLatest = race.start();     // ١) أبطِل مفعول كل ما سبق
       const snapshot = readInputs();     // ٢) لقطة مدخلات
       const data = await fetch(...);     // ٣) انتظار
       if (!isLatest()) return;           // ٤) بوابة الالتزام
       commit(data);                      // ٥) كتابة ذرّية
     }

   قاعدة الاستخدام الوحيدة
   ───────────────────────
   لا تكتب على أي حالة مشتركة قبل بوابة الالتزام. احسب في متغيّرات
   محلية ثم التزم دفعةً واحدة بعد isLatest() — وإلا سرّبَ الطلبُ
   المتجاوَز جزءًا من حالته رغم الحارس.
   ================================================================ */

/**
 * يُنشئ حارسًا مستقلًا لمسار تحميل واحد.
 * استخدم حارسًا لكل مسار منطقي منفصل (شبكة المساحات، قائمة الإعلانات…)
 * حتى لا يُبطل مسارٌ نتائجَ مسارٍ آخر لا علاقة له به.
 * @returns {{ start: () => (() => boolean), issued: number }}
 */
function createRaceGuard() {
  let seq = 0;

  return {
    /**
     * يسجّل محاولة جديدة ويُبطل مفعول كل محاولة سابقة.
     * @returns {() => boolean} دالة تُجيب: هل ما زالت هذه المحاولة هي الأحدث؟
     *   تُستدعى بعد كل await وقبل أي كتابة على حالة مشتركة.
     */
    start() {
      const mine = ++seq;
      return () => mine === seq;
    },

    /** عدد المحاولات التي أُطلقت — للتشخيص والاختبار فقط */
    get issued() { return seq; },
  };
}
